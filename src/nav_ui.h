#pragma once
#include "lvgl.h"
#include "nav_state.h"

// ============================================================
// 导航页（左屏，阶段 A）
//
// 形态（车主 2026-11-21 定）：
//   上方   大号**转向指示**（左转/右转/直行/掉头/匝道/到达…，跟着 `NavTurn` 变）
//   中间   **到路口距离**（<1 km 显米、≥1 km 显 0.1 km，见 `nav_dist_value`）
//   下方   车图标（**图片指针**）：随 `heading_cdeg` 旋转，代表"车头朝哪"；
//          阶段 A 是几何占位，等车主给车标 PNG 后换成图片角色（主题 R6）
//   右下   车速数字（高德 `CUR_SPEED`；右屏 OBD 车速是另一路，互不干扰）
//   没数据 整页变暗 + "NO NAV"（**不显示过期数据**，判据在 nav_state.h）
//
// ★ 为什么先做成"几何占位"而不是等图片：图片指针要主题 R6 + 新图片角色 + 编辑器，
//   那是阶段 B；阶段 A 先把"数据 → 位置/角度/文案"这条链路跑通并落帧验证，
//   换图只是把 `draw_car()` 换成 `lv_image`，判据与布局都不用动。
// ============================================================

// 在指定显示的当前活动屏上铺一层导航页（480×480，不透明，盖住底下的表盘）。
void nav_ui_attach(lv_display_t* disp);

// 数据驱动：只在**值变了**的时候重排（保持"一次写入、不逐帧重绘"的纪律）。
void nav_ui_update(const NavState& s);

// 预览专用：没有真实 BLE 源时，用时间戳合成一串"看起来像在导航"的数据，
// 好让 pcpreview 的落帧能验证布局/旋转/文案。**只在 DASH_DISPLAY_PREVIEW 下存在。**
void nav_ui_preview_tick(uint32_t now_ms);

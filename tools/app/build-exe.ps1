# Build the 206Dash workbench into a single .exe (PyInstaller).
#
#   powershell -ExecutionPolicy Bypass -File tools\app\build-exe.ps1
#
# WHY THIS EXISTS: the user asked "can't it be packaged into an executable?".
#   The app is a stdlib-only Python server + a handful of static files, so packaging
#   is boring on purpose -- no dependency hell. What DOES need care is that the exe
#   must still find the repository (that is where PlatformIO lives, and where the
#   preview frames come from), so:
#     * the app files AND the editor's static files are embedded (--add-data) so the
#       UI and the editor (colors + images) work with no repository in sight;
#     * the exe locates the repo itself (see find_repo() in server.py), and
#       --repo lets you point it explicitly;
#     * console build (not --noconsole) so the log stays visible, and the UI has
#       a "quit" button that stops the server cleanly.
#
#   WHERE THE EDITOR FILE LIST COMES FROM (do not guess it):
#     started the server and loaded it with a headless browser, then read the
#     request log -- the GETs for the editor page are exactly the 7 files below
#     (see ALLOWED_EDITOR_FILES in server.py). /favicon.ico is the browser asking
#     for something that was already a 404; preview/* is generated by the repo and
#     still requires the repo, so it is deliberately NOT embedded.
#     esptool / PlatformIO / firmware bins are never embedded either.
#
# ASCII only (PowerShell 5.1 reads BOM-less .ps1 as GBK).
param(
  [string]$Name = '206Dash-Workbench',
  [string]$OutDir,
  [switch]$OneFile
)

$ErrorActionPreference = 'Continue'
$here = $PSScriptRoot                       # ...\tools\app
$repo = Split-Path (Split-Path $here -Parent) -Parent
$editor = Join-Path $repo 'tools\theme-editor'
if (-not $OutDir) { $OutDir = Join-Path $here 'dist' }

# the python that carries PyInstaller (the project venv; falls back to PATH)
$py = 'C:\206dash-scratch\pio-core-mix\penv\Scripts\python.exe'
if (-not (Test-Path $py)) { $py = 'python' }

Write-Host "repo   : $repo"
Write-Host "python : $py"
Write-Host ("mode   : " + $(if ($OneFile) { 'onefile (single .exe, ~1-2s startup)' } else { 'onedir (folder, faster startup)' }))

# PyInstaller writes its work next to the spec; keep both inside tools\app\build
$work = Join-Path $here 'build'
$spec = Join-Path $here 'build'

# the editor files that MUST be inside the exe (the recorded request list);
# bail out loudly instead of shipping an exe whose editor would 404.
$editorFiles = @(
  'index.html',              # the one implementation, two in-page parts
  'image-editor.html',       # redirect shell, so old bookmarks keep working
  'face-stages.js',
  'image-blob-build.js',
  'asset-spec.js',
  'theme-json.js',
  'asset-package-core.js'
)
$missing = @()
foreach ($f in $editorFiles) { if (-not (Test-Path (Join-Path $editor $f))) { $missing += $f } }
if ($missing.Count -gt 0) {
  Write-Host "FAILED: missing editor files under $editor :"
  $missing | ForEach-Object { Write-Host "  - $_" }
  exit 1
}

$args = @(
  '-m', 'PyInstaller',
  '--noconfirm', '--clean',
  '--name', $Name,
  '--distpath', $OutDir,
  '--workpath', $work,
  '--specpath', $spec,
  # embed the UI so the app opens without a repo
  '--add-data', "$here\index.html;tools/app",
  '--add-data', "$here\app.css;tools/app",
  '--add-data', "$here\app.js;tools/app",
  '--add-data', "$here\README.md;tools/app",
  # embed the editor's static files (exact list = the recorded request log).
  # server.py serves the repo copy first and falls back to these.
  '--add-data', "$editor\index.html;tools/theme-editor",
  '--add-data', "$editor\image-editor.html;tools/theme-editor",
  '--add-data', "$editor\face-stages.js;tools/theme-editor",
  '--add-data', "$editor\image-blob-build.js;tools/theme-editor",
  '--add-data', "$editor\asset-spec.js;tools/theme-editor",
  '--add-data', "$editor\theme-json.js;tools/theme-editor",
  '--add-data', "$editor\asset-package-core.js;tools/theme-editor",
  # console build: the log is the point (and --noconsole would hide it)
  '--console'
)
if ($OneFile) { $args += '--onefile' }
$args += (Join-Path $here 'server.py')

Write-Host "running: $py $($args -join ' ')"
& $py @args 2>&1 | Select-Object -Last 12

$exe = if ($OneFile) { Join-Path $OutDir "$Name.exe" } else { Join-Path $OutDir "$Name\$Name.exe" }
if (Test-Path $exe) {
  $f = Get-Item $exe
  Write-Host ""
  Write-Host "OK -> $($f.FullName)"
  Write-Host ("     {0:N1} MB   {1}" -f ($f.Length / 1MB), $f.LastWriteTime)
  Write-Host ""
  Write-Host "run it:"
  Write-Host "  `"$($f.FullName)`"                       # auto-detects the repo, opens the browser"
  Write-Host "  `"$($f.FullName)`" --app-window          # chromeless window"
  Write-Host "  `"$($f.FullName)`" --repo <repo path>    # point it at the repo explicitly"
  Write-Host "  `"$($f.FullName)`" --port 8899 --no-open"
  Write-Host ""
  Write-Host "without a repo the editor still works (colors + images + assets.bin);"
  Write-Host "building firmware and the preview need the repo and will say which path is missing."
} else {
  Write-Host "FAILED: no exe at $exe"
  exit 1
}

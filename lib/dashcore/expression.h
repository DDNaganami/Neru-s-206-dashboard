#pragma once
#include <stdint.h>
#include "vehicle_state.h"

// ============================================================
// 表情状态机 —— **每屏一套，各看各的表**
//
// 左屏 = 转速表：只看转速
// 右屏 = 速度表：只看车速
// 水温**不参与表情**（见下）。
//
// 枚举是**两屏共用的档位名**（槽位顺序就是这个顺序），但每屏只用其中四个：
//   左屏：Idle(低) / Cruise(中) / Sport(高) / Redline(红区)
//   右屏：Idle(低) / Cruise(中) / Sport(高) / Overspeed(超速)
// 哪一屏用哪几个由 lib/dashcore/face_stages.h 的 kFaceLeftStates /
// kFaceRightStates 明确列出，并由测试断言"列出的状态必须有图、没列出的必须没有"。
//
// 为什么两屏共用一个枚举而不是各写一个：
//   图片角色、降级链、阶段表都是"按槽位"组织的，一个枚举让它们能共用一张表；
//   每屏**实际能产生哪些状态**由各自的状态机决定（见 expression.cpp），
//   这才是"独立"的地方 —— 而不是枚举类型不同。
//
// 为什么水温不参与表情（用户决定）：
//   · 一套水温表情要再加 4 张图（冷车/过热 × 左右屏），而 image 分区只有
//     1MB —— 240×240 一张 169KB，8 张表情 + 背景就已经贴到上限了；
//   · 水温是慢变量，屏幕底下本来就有水温弧和水温数字，再让脸也跟着变，
//     信息重复且容易误读（看到冷车脸会以为车有问题，其实只是刚启动）。
//   于是 Cold/Hot 两个状态**删除**，水温只驱动"弧 + 数字"。
//   编号 14/15/19/20（当年的冷车/过热图）作为保留编号留空不复用。
//
// 编号 11/16（当年的"眨眼"图）同理留着，原因见 image_blob.h。
//
// ★ 槽位 4 的来历（2026 年改）：原来是 Surprise「惊喜·急加速瞬态」。
//   它的阈值是"速度变化率 > 15 km/h/s"，结果两头不讨好：
//   实车上 206 CC 自动挡根本到不了那个加速度（0-100 约 11s），
//   模拟器的"车速低/中/高"三个按钮里也没有它的位置 —— 用户试用时
//   直接问"这个惊喜档测的时候选不出来，是做什么用的"。
//   于是改成 **Overspeed 超速（车速 > 130 km/h）**：稳态、可模拟、上高速会遇到。
//   槽位下标仍然是 4、图片角色编号仍然是 8（右屏）—— **名字变了，号没变**，
//   别人手里已经导出的 image.bin 不受影响。详见 expression.cpp 顶部。
// ============================================================
enum class Face : uint8_t {
  Idle = 0,     // 低：转速 < 1800（左）/ 车速 < 30（右）
  Cruise,       // 中：转速 >= 1800（左）/ 车速 >= 30（右）
  Sport,        // 高：转速 >= 3500（左）/ 车速 >= 90（右）
  Redline,      // 红区：转速 >= 5000（按 6000 表盘标定,表盘更正为 7000 后待重排）—— **只有左屏（转速表）会产生**
  Overspeed,    // 超速：车速 > 130（退出 <= 127，迟滞）—— **只有右屏（速度表）会产生**
  Count
};
// ★ 上面的数字是**实车标定值**，唯一权威定义在 expression.cpp 顶部的
//   kRpmCruiseFrom / kRpmSportFrom / kRpmRedlineFrom（1800 / 3500 / 5000）。
//   这里以前抄的是旧值 2500/4500/6000，已经在真车上被否掉了
//   （那套值等于"巡航时还显示常态脸、红区只有断油才亮"）——
//   改阈值时**三处一起改**：expression.cpp、face_stages.h 的阶段表、这里。

// 一屏一个表情，两屏合起来就是这一帧该显示的两张脸
struct FaceSet {
  Face left;    // 左屏 = 转速表
  Face right;   // 右屏 = 速度表
};

// 状态机的记忆。
// ★ 现在只剩**一个** bool（超速迟滞位，在 expression.cpp 里），所以这里
//   不再有 FaceState 结构体 —— 眨眼删了、惊喜（瞬态）改成超速（稳态）之后，
//   表情**只由数据决定，与时间无关**（有单测钉住这一点）。
FaceSet face_update(const VehicleState& s, uint32_t now);
const char* face_name(Face f);

// 清空状态机的记忆（超速迟滞位）。
// 用途：换数据源（模拟↔OBD）时，避免"上一个源还在 140 km/h"让新源在
// 127..130 之间继续报超速；宿主机测试里逐条跑阶段用例时也要先清。
void face_reset();

#pragma once
#include <stdint.h>
#include "vehicle_state.h"

// ============================================================
// 表情状态机 —— **每屏一套，各看各的表**
//
// 左屏 = 转速表：只看转速
// 右屏 = 速度表：只看车速（外加"急加速"这个瞬态）
// 水温**不参与表情**（见下）。
//
// 枚举是**两屏共用的档位名**（槽位顺序就是这个顺序），但每屏只用其中四个：
//   左屏：Idle(低) / Cruise(中) / Sport(高) / Redline(红区)
//   右屏：Idle(低) / Cruise(中) / Sport(高) / Surprise(惊喜,瞬态)
// 哪一屏用哪几个由 lib/dashcore/face_stages.h 的 kFaceLeftStates /
// kFaceRightStates 明确列出，并由测试断言"列出的状态必须有图、没列出的必须没有"。
//
// 为什么两屏共用一个枚举而不是各写一个：
//   图片角色、降级链、阶段表都是"按槽位"组织的，一个枚举让它们能共用一张表；
//   每屏**实际能产生哪些状态**由各自的状态机决定（见 expression.cpp），
//   这才是"独立"的地方 —— 而不是枚举类型不同。
//
// 为什么水温不参与表情（用户决定）：
//   · 一套水温表情要再加 4 张图（冷车/过热 × 左右屏），而 image 分区只有
//     1MB —— 240×240 一张 169KB，8 张表情 + 背景就已经贴到上限了；
//   · 水温是慢变量，屏幕底下本来就有水温弧和水温数字，再让脸也跟着变，
//     信息重复且容易误读（看到冷车脸会以为车有问题，其实只是刚启动）。
//   于是 Cold/Hot 两个状态**删除**，水温只驱动"弧 + 数字"。
//   编号 14/15/19/20（当年的冷车/过热图）作为保留编号留空不复用。
//
// 编号 11/16（当年的"眨眼"图）同理留着，原因见 image_blob.h。
// ============================================================
enum class Face : uint8_t {
  Idle = 0,     // 低：转速 < 2500（左）/ 车速 < 30（右）
  Cruise,       // 中：转速 >= 2500（左）/ 车速 >= 30（右）
  Sport,        // 高：转速 >= 4500（左）/ 车速 >= 90（右）
  Redline,      // 红区：转速 >= 6000 —— **只有左屏（转速表）会产生**
  Surprise,     // 惊喜：急加速 > 15 km/h/s，瞬时 400ms —— **只有右屏会产生**
  Count
};

// 一屏一个表情，两屏合起来就是这一帧该显示的两张脸
struct FaceSet {
  Face left;    // 左屏 = 转速表
  Face right;   // 右屏 = 速度表
};

// 状态机的记忆：只有"惊喜持续到什么时候"。
// 两个稳态各自按当前数据现算，不需要记住上一次是什么 ——
// 所以表情**只由数据决定，与时间无关**（有单测钉住这一点）。
struct FaceState {
  Face face;
  uint32_t until_ms;
};
FaceSet face_update(const VehicleState& s, uint32_t now);
const char* face_name(Face f);

// 清空状态机的记忆(上一次速度/时刻/瞬态截止时间)。
// 用途:换数据源(模拟↔OBD)时避免把"两个源之间的速度差"误判成急加速;
// 宿主机测试里逐条跑阶段用例时也必须先清,否则上一条用例的速度会串进加速度。
void face_reset();

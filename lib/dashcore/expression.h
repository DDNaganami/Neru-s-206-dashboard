#pragma once
#include <stdint.h>
#include "vehicle_state.h"

// ============================================================
// 表情状态机
//
// 每个状态对应**一张可导入的差分图**(左屏 7 张 / 右屏 7 张,见 image_blob.h)。
// 枚举顺序就是表情图的槽位顺序 —— dash_ui 直接用 (int)Face 当下标,
// 所以**只能在 Count 之前追加**,不能插队(会让已导入的图错位)。
//
// 状态从哪来?三路数据各有一条"低/中/高"分档,优先级从高到低:
//   惊喜(急加速,瞬时 400ms) > 红区(转速) > 过热(水温) > 冷车(水温)
//   > 运动(速度或转速高) > 巡航(速度或转速中) > 常态
// 分档阈值集中在 expression.cpp 顶部,阶段用例表在 face_stages.h,
// 两边由 test_face_stages.cpp 钉住 —— 改阈值必须同步改那张表。
//
// ★ 曾经有过 Blink(眨眼)状态,已删除。原因:
//   · 它和时间有关、**与车速/转速/水温都无关**,所以既讲不出"什么工况下会眨眼",
//     也没法在阶段模拟里体现(用户原话:"和车速状态无关也不好展现");
//   · 用图片表情时它本来也几乎看不出来 —— 没导入眨眼图就退到常态那张,
//     等于什么都没发生;
//   · 顺带把"周期性 set_text/切图"这类无谓重绘一起去掉了。
//   编号 11 / 16(当年左右屏的眨眼图)作为**保留编号**留着不回收,理由见 image_blob.h。
// ============================================================
enum class Face : uint8_t {
  Idle = 0,     // 常态(转速/速度都低、水温正常)
  Cruise,       // 巡航(速度 >= 30 或转速 >= 2500)
  Sport,        // 运动(速度 >= 90 或转速 >= 4500)
  Redline,      // 红区(转速 >= 6000)
  Surprise,     // 惊喜(急加速,瞬时 400ms)
  Cold,         // 冷车(水温 < 70:暖机中)
  Hot,          // 过热(水温 >= 105)
  Count
};

// 状态机的记忆。只有"当前状态 + 瞬态截止时刻"两件事:
// 稳态由 face_update 每次按当前数据现算,不需要记住上一次是什么。
struct FaceState {
  Face face;
  uint32_t until_ms;   // 瞬态(惊喜)持续到这个时刻
};
Face face_update(const VehicleState& s, uint32_t now);
const char* face_name(Face f);


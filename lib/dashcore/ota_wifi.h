#pragma once

// ============================================================================
// ota_wifi —— **按需** WiFi 无线刷写（串口敲 `u` 进入）
// ============================================================================
//
// 为什么是"按需 + 重启进入"，而不是"常驻一个 HTTP 服务"：
//   ① **零稳态代价**：WIFI AP + HTTP + Update 要几十 KB 内部 RAM，而两块板都不宽裕
//      （从板带 BLE 时稳态只剩 ~29 KB，还要喂 RGB 面板的弹跳缓冲）⇒ 常驻会直接
//      吃掉余量，还可能把面板的连续块挤碎；
//   ② **不碰射频共存**：ESP-NOW 在 STA 上、频道是 6，而 SoftAP 会改频道 ——
//      现场把两者拆开（进 OTA 时链路/ OBD 都不启动）比"让它们互相让"干净得多；
//   ③ **状态干净**：上传成功要重启（A/B 槽生效），失败退出也重启 ⇒ 没有"半个
//      初始化的状态"要收拾。
//
// 流程（`u` 敲下之后）：
//   串口 `u` → 置 RTC 标志 + `ESP.restart()` → 开机看到标志 ⇒ `ota_wifi_run()`：
//   起 AP `206dash-<ROLE>` + 一个上传页 → 手机浏览器上传 `firmware.bin`
//   → 写进**另一个** OTA 槽 → 成功/超时都 `ESP.restart()` 回到正常固件。
//
// ★ 标志放在 **RTC_NOINIT**（软件复位保留、**断电丢失**）：这正是想要的语义 ——
//   "用户按了 u 要刷机"这件事不该跨过一次断电（否则一次断电就会把板子永久留在
//   OTA 模式里，只能再刷一次 USB）。同一手法见 `main.cpp` 里那个从板重启计数器。
//
// ★ 只在 `ARDUINO && DASH_OTA` 的构建里编：其余构建（pcpreview / 抓帧盒 / 默认档）
//   一行都进不去 ⇒ 行为与加这一层之前逐字节相同。
#if defined(ARDUINO) && defined(DASH_OTA)

namespace dashcore {

// 串口 `u` 调它：置标志 + 重启（**不返回**）。
void ota_wifi_request();

// `setup()` 里调：读到"用户要刷机"就返回 true 并**清掉标志**。
// 为什么要"取一次"而不是"查一次"：清掉之后，万一 OTA 自己崩了、板子重启，
// 下一次开机就是**正常固件**，不会卡在 OTA 模式里反复起 AP。
bool ota_wifi_take_request();

// 跑 OTA 服务（**阻塞、成功或超时都 `ESP.restart()`，永不返回**）。
void ota_wifi_run();

// 给开机横幅用：这一档到底支不支持无线刷写（DASH_OTA 构建里恒 true）。
bool ota_wifi_supported();

}  // namespace dashcore

#endif  // ARDUINO && DASH_OTA

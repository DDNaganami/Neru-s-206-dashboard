#pragma once
#include <stdint.h>

// ============================================================
// 阶梯分档 + 迟滞（Schmitt 触发）—— 纯函数，宿主机可测
//
// 为什么单独抽出来：
//   分档判据是"表情会不会在边界上闪"的唯一决定点，而它错起来很隐蔽
//   （看起来只是"脸偶尔跳一下"）。抽成纯函数才能在宿主机上把每条边界
//   的两个方向都钉死，见 test_expression.cpp 的 test_face_ladder_hysteresis。
//
// 为什么每条边界都要迟滞（2026-09-18 加）：
//   这台车的 AL4 会在边界附近**停住**：
//     · 液力变矩器锁止/解锁，同一车速下转速差 200~300 转；
//     · 4 档巡航 100~130km/h 正好是 2600~3400 转 —— 紧贴"巡航→运动"的分界；
//     · 定速巡航时车速会在阈值上下 1~2km/h 抖。
//   没有迟滞就会来回切脸。迟滞量必须**大于**要吸收的抖动：
//   转速取 100（锁止那 200~300 转靠边界位置躲开，不靠迟滞硬扛）。
//
// 用法：把阈值按升序排好，`cur` 传上一次算出的档位下标（0 = 最低档）。
// 返回值 = 这次该在的档位下标，范围 0..n。
// ============================================================
inline uint8_t ladderStep(float v, const float* thr, uint8_t n, float hyst,
                          uint8_t cur) {
  uint8_t idx = 0;
  for (uint8_t i = 0; i < n; ++i) {
    // 已经在第 i 档以上：只要没掉到 thr[i]-hyst 以下就留在原档；
    // 还在第 i 档以下：必须涨到 thr[i]+hyst 才进档。
    // —— 这就是迟滞：两个方向的门槛差 2*hyst。
    const bool already_up = (cur > i);
    const float gate = already_up ? (thr[i] - hyst) : (thr[i] + hyst);
    if (v >= gate) idx = (uint8_t)(i + 1);
  }
  return idx;
}
